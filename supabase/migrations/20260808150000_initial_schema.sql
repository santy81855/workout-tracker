  weight_unit text not null default 'lb' check (weight_unit = 'lb'),
  default_increment_tenths_lb integer not null default 25 check (default_increment_tenths_lb > 0),
  theme text not null default 'system' check (theme in ('system', 'light', 'dark')),
  dark_mode_bias boolean not null default true,
