  slug text,
  name text not null,
  equipment_type text not null,
  load_basis public.load_basis not null,
  default_rep_min smallint check (default_rep_min > 0),
  default_rep_max smallint check (default_rep_max > 0),
  default_increment_tenths_lb integer check (default_increment_tenths_lb > 0),
  minimum_load_tenths_lb integer check (minimum_load_tenths_lb >= 0),
  maximum_load_tenths_lb integer check (maximum_load_tenths_lb >= 0),
  valid_loads_tenths_lb integer[],
  default_rest_seconds integer check (default_rest_seconds between 30 and 600),
  guidance text[] not null default '{}',
  technique_check text check (technique_check in ('squat', 'rdl')),
  is_curated boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
