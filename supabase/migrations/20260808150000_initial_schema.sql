  notes text,
  constraint exercise_substitution_distinct check (source_exercise_id <> replacement_exercise_id)
);

create unique index exercise_substitutions_curated_key
on public.exercise_substitutions(source_exercise_id, replacement_exercise_id)
where owner_user_id is null;
create unique index exercise_substitutions_owner_key
on public.exercise_substitutions(source_exercise_id, replacement_exercise_id, owner_user_id)
where owner_user_id is not null;

create table public.programs (
