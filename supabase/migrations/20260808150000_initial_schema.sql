begin;

create extension if not exists pgcrypto;

create type public.load_basis as enum (
  'external_total',
  'per_dumbbell',
  'added_bodyweight',
  'bodyweight_only',
  'assistance',
  'repetition_only'
);

create type public.cycle_status as enum ('planned', 'active', 'completed', 'abandoned');
create type public.scheduled_workout_status as enum ('queued', 'active', 'completed', 'partial', 'skipped');
create type public.session_status as enum ('active', 'completed', 'partial', 'abandoned');
create type public.session_exercise_status as enum ('pending', 'active', 'completed', 'partial', 'skipped');
create type public.exercise_set_status as enum ('draft', 'completed', 'skipped', 'deleted');

create function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
