  constraint exercises_name_present check (char_length(trim(name)) between 1 and 120),
  constraint exercises_slug_format check (slug is null or slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint exercises_rep_range check (
    default_rep_min is null or default_rep_max is null or default_rep_min <= default_rep_max
  ),
  constraint exercises_load_range check (
    minimum_load_tenths_lb is null or maximum_load_tenths_lb is null
    or minimum_load_tenths_lb <= maximum_load_tenths_lb
  ),
  constraint exercises_curated_ownership check (
    (is_curated and owner_user_id is null) or (not is_curated and owner_user_id is not null)
  )
);

create unique index exercises_curated_slug_key on public.exercises(slug) where owner_user_id is null;
create unique index exercises_owner_name_key on public.exercises(owner_user_id, lower(name)) where owner_user_id is not null;

create table public.exercise_muscles (
  exercise_id uuid not null references public.exercises(id) on delete cascade,
  muscle_group_id smallint not null references public.muscle_groups(id) on delete restrict,
  owner_user_id uuid references public.profiles(id) on delete cascade,
  contribution_tenths smallint not null check (contribution_tenths in (5, 10)),
  role text not null check (role in ('primary', 'secondary')),
  primary key (exercise_id, muscle_group_id),
  constraint exercise_muscles_role_contribution check (
